export function classify(relativePath, fileName, content = '') {
  const value = `${relativePath} ${fileName} ${content}`;
  const jurisdiction = /台灣|臺灣|臺灣地區|TW\b|中華民國|台湾|中国台湾/iu.test(value)
    ? 'TW'
    : /中國大陸|中华人民共和国|中国|重慶|重庆|河南|山東|山东|江蘇|江苏|浙江|湖北|廣東|广东|CN\b/iu.test(value)
      ? 'CN'
      : 'UNKNOWN';

  const topicHits = topicRules.filter(([, rule]) => rule.test(value)).map(([topic]) => topic);
  const type = typeRules.find(([, rule]) => rule.test(value))?.[0] ?? '待確認或非規範文件';
  const primaryTopic = topicHits[0] ?? '其他／待確認';

  return {
    jurisdiction,
    documentType: type,
    primaryTopic,
    secondaryTopics: topicHits.slice(1),
    confidence: primaryTopic === '其他／待確認' || jurisdiction === 'UNKNOWN' ? 0.35 : 0.75
  };
}
